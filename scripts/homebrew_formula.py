#!/usr/bin/env python3
"""Render wired-magic.rb only from verified release archives (stdlib only)."""
import argparse
import hashlib
from pathlib import Path
import re
import tarfile


ARCHS = ("arm64", "x86_64")


def render(repository, tag, assets, archs=ARCHS):
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("repository must be owner/repository")
    if not re.fullmatch(r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", tag):
        raise ValueError("tag must be stable SemVer vMAJOR.MINOR.PATCH")
    archs = tuple(archs)
    if not archs or len(set(archs)) != len(archs) or any(a not in ARCHS for a in archs):
        raise ValueError(f"archs must be a non-empty subset of {ARCHS}")
    hashes = {}
    for arch in archs:
        name = f"wired-magic-{tag}-darwin-{arch}.tar.gz"
        archive = assets / name
        with tarfile.open(archive, "r:gz") as bundle:
            members = bundle.getmembers()
            if len(members) != 1 or members[0].name != "wm" or not members[0].isfile() or not members[0].mode & 0o111:
                raise ValueError(f"{name} must contain only executable wm")
        hashes[arch] = hashlib.sha256(archive.read_bytes()).hexdigest()
    expected = "".join(f"{hashes[a]}  wired-magic-{tag}-darwin-{a}.tar.gz\n" for a in archs)
    if (assets / "SHA256SUMS").read_text() != expected:
        raise ValueError("SHA256SUMS does not match release archives")
    base = f"https://github.com/{repository}"
    arch_dep = ""
    if archs == ("arm64",):
        arch_dep = "  depends_on arch: :arm64\n"
    elif archs == ("x86_64",):
        arch_dep = "  depends_on arch: :x86_64\n"
    # Homebrew validates taps for Linux too, where the on_macos block is not
    # evaluated. A default spec keeps the formula readable there; depends_on
    # :macos still prevents Linux installation.
    primary = "arm64" if "arm64" in hashes else "x86_64"
    primary_url = f"{base}/releases/download/{tag}/wired-magic-{tag}-darwin-{primary}.tar.gz"
    blocks = []
    if "arm64" in hashes:
        blocks.append(f'''    on_arm do
      url "{base}/releases/download/{tag}/wired-magic-{tag}-darwin-arm64.tar.gz"
      sha256 "{hashes['arm64']}"
    end
''')
    if "x86_64" in hashes:
        blocks.append(f'''    on_intel do
      url "{base}/releases/download/{tag}/wired-magic-{tag}-darwin-x86_64.tar.gz"
      sha256 "{hashes['x86_64']}"
    end
''')
    return f'''# Generated by scripts/homebrew_formula.py; do not edit checksums by hand.
class WiredMagic < Formula
  desc "Self-hosted VPN mesh"
  homepage "{base}"
  version "{tag[1:]}"
  license "MIT"

  url "{primary_url}"
  sha256 "{hashes[primary]}"
  depends_on :macos
{arch_dep}
  on_macos do
    depends_on macos: :sonoma
{"".join(blocks)}  end

  def install
    bin.install "wm"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/wm --version")
  end
end
'''


def ensure_monotonic(existing, candidate):
    """Refuse unknown existing versions and downgrades; allow identical retries."""
    def version(text):
        declarations = re.findall(r'^\s*version\s+"([^"]+)"\s*$', text, re.MULTILINE)
        if len(declarations) != 1 or not re.fullmatch(
            r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', declarations[0]
        ):
            raise ValueError('formula must declare exactly one explicit stable version')
        return tuple(map(int, declarations[0].split('.')))
    new = version(candidate)
    if existing.exists() and version(existing.read_text()) > new:
        raise ValueError('refusing to downgrade existing tap formula')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", required=True)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--assets", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument(
        "--archs",
        choices=("both", "arm64", "x86_64"),
        default="both",
        help="Architectures present in --assets (default: both)",
    )
    parser.add_argument("--existing", type=Path, help="Existing tap formula; refuse downgrades")
    args = parser.parse_args()
    archs = ARCHS if args.archs == "both" else (args.archs,)
    result = render(args.repository, args.tag, args.assets, archs)
    if args.existing is not None:
        ensure_monotonic(args.existing, result)
    args.output.write_text(result)


if __name__ == "__main__":
    main()
